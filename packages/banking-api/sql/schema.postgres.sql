-- The same ledger as schema.sql, for Postgres (DATABASE_URL). Same tables, columns, names and
-- rules, so the SQL ledger checks in sql/checks run unchanged on both. What differs:
--   * ids are BIGINT identity columns; BY DEFAULT, so a defect test can still insert its own id
--   * amounts are BIGINT, exact up to 9.2 * 10^18 (the limit, 10^17 - 1 a currency, fits);
--     a SUM of BIGINT is NUMERIC on Postgres, so no total can overflow either
--   * times stay ISO 8601 text, as in SQLite, so the same comparisons work on both
-- Foreign keys are always on here: a defect test turns them off for its own session with
-- session_replication_role = replica, as another tool with the rights could.

CREATE TABLE IF NOT EXISTS accounts (
  id         BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       TEXT    NOT NULL CHECK (kind IN ('customer', 'funding')),
  owner      TEXT    NOT NULL,
  currency   TEXT    NOT NULL CHECK (currency IN ('CAD', 'USD', 'JPY', 'KWD')),
  created_at TEXT    NOT NULL
);

-- One funding account per currency (BK-R14). Two first deposits at once both try to make it:
-- the index lets one in, and the other finds it (ON CONFLICT in src/postgres.ts).
CREATE UNIQUE INDEX IF NOT EXISTS one_funding_account_per_currency
  ON accounts (currency) WHERE kind = 'funding';

CREATE TABLE IF NOT EXISTS transfers (
  id              BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind            TEXT    NOT NULL CHECK (kind IN ('deposit', 'withdrawal', 'transfer')),
  from_account_id BIGINT  NOT NULL REFERENCES accounts (id),
  to_account_id   BIGINT  NOT NULL REFERENCES accounts (id),
  amount          BIGINT  NOT NULL CHECK (amount > 0),
  currency        TEXT    NOT NULL,
  created_at      TEXT    NOT NULL,
  reference       TEXT    CHECK (reference IS NULL OR length(reference) BETWEEN 1 AND 35),  -- BK-R38
  CHECK (from_account_id <> to_account_id)
);

CREATE INDEX IF NOT EXISTS transfers_sent_by_day ON transfers (from_account_id, created_at);

CREATE TABLE IF NOT EXISTS ledger_entries (
  id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_id BIGINT  NOT NULL REFERENCES transfers (id),
  account_id  BIGINT  NOT NULL REFERENCES accounts (id),
  amount      BIGINT  NOT NULL CHECK (amount <> 0),  -- negative: debit, positive: credit
  currency    TEXT    NOT NULL
);

CREATE INDEX IF NOT EXISTS ledger_entries_by_account ON ledger_entries (account_id, id);
CREATE INDEX IF NOT EXISTS ledger_entries_by_transfer ON ledger_entries (transfer_id);

CREATE TABLE IF NOT EXISTS idempotency_keys (
  key         TEXT    PRIMARY KEY,
  fingerprint TEXT    NOT NULL,
  transfer_id BIGINT  UNIQUE REFERENCES transfers (id),
  created_at  TEXT    NOT NULL
);

CREATE INDEX IF NOT EXISTS idempotency_keys_by_age ON idempotency_keys (created_at);

CREATE TABLE IF NOT EXISTS screening_decisions (
  id              BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decided_at      TEXT    NOT NULL,
  kind            TEXT    NOT NULL CHECK (kind IN ('deposit', 'withdrawal', 'transfer')),
  from_account_id BIGINT  REFERENCES accounts (id),
  to_account_id   BIGINT  REFERENCES accounts (id),
  amount          BIGINT  NOT NULL CHECK (amount > 0),
  currency        TEXT    NOT NULL,
  decision        TEXT    NOT NULL CHECK (decision IN ('allowed', 'reported', 'held', 'blocked')),
  rule            TEXT,
  detail          TEXT    NOT NULL,
  CHECK ((decision = 'allowed') = (rule IS NULL))
);
