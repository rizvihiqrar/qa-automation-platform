// Scores every recorded judge run against the human labels and writes REPORT.md and
// results/summary.json.
//
// node src/report.ts          writes both
// node src/report.ts --check  fails if the committed files are out of date (CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { badCitations } from './attribution.ts';
import { lf, type KeyEntry } from './build-cases.ts';
import { loadRuns, type Run } from './record.ts';
import { loadItems, PKG } from './render.ts';
import { loadKey } from './review-sheet.ts';
import {
  agreement,
  confusion,
  describeKappa,
  flagged,
  kappa,
  kappaInterval,
  majority,
  unanimous,
  VERDICTS,
  type Verdict,
} from './stats.ts';

const pct = (x: number) => (Number.isNaN(x) ? 'n/a' : `${Math.round(x * 100)}%`);
const k2 = (x: number) => (Number.isNaN(x) ? 'n/a' : x.toFixed(2));
const ci = (i: { low: number; high: number }, f: (x: number) => string) => `${f(i.low)}–${f(i.high)}`;

export interface Scored {
  judge: string;
  runs: string[];
  ids: string[];
  human: Verdict[];
  verdicts: Verdict[];
}

/** One judge's verdicts on the given cases; several runs are combined by majority vote. */
export function score(judge: string, runs: Run[], ids: string[], key: Record<string, KeyEntry>): Scored {
  const verdictsOf = (run: Run) => ids.map((id) => run.answers.find((a) => a.id === id)?.verdict as Verdict);
  const all = runs.map(verdictsOf);
  return {
    judge,
    runs: runs.map((r) => r.name),
    ids,
    human: ids.map((id) => (key[id] as KeyEntry).label),
    verdicts: ids.map((_, i) => majority(all.map((v) => v[i] as Verdict))),
  };
}

export function summarize(s: Scored) {
  const a = agreement(s.human, s.verdicts);
  const k = kappa(s.human, s.verdicts);
  const wk = kappa(s.human, s.verdicts, true);
  return {
    judge: s.judge,
    cases: s.ids.length,
    agree: a.agree,
    agreement: a.rate,
    agreementCi: a.ci,
    kappa: k,
    kappaCi: kappaInterval(s.human, s.verdicts),
    weightedKappa: wk,
    flags: flagged(s.human, s.verdicts),
    confusion: confusion(s.human, s.verdicts),
    wrong: s.ids.filter((_, i) => s.human[i] !== s.verdicts[i]).map((id) => ({ id, human: s.human[s.ids.indexOf(id)], judge: s.verdicts[s.ids.indexOf(id)] })),
  };
}

function build(): { report: string; summary: string } {
  const key = loadKey();
  const items = loadItems();
  const runs = loadRuns();
  const judges = [...new Set(runs.map((r) => r.name.replace(/-\d+$/, '')))].sort();
  const runsOf = (judge: string) => runs.filter((r) => r.name.replace(/-\d+$/, '') === judge);
  const ids = (round?: 1 | 2) => items.filter((i) => round === undefined || (key[i.id] as KeyEntry).round === round).map((i) => i.id);
  const answered = (judge: string, set: string[]) => set.filter((id) => runsOf(judge).every((r) => r.answers.some((a) => a.id === id)));

  const sets: { name: string; ids: string[] }[] = [
    { name: 'All cases', ids: ids() },
    { name: 'Round 1 (59 cases)', ids: ids(1) },
    { name: 'Round 2 (subtler variants)', ids: ids(2) },
    { name: 'Real criteria only', ids: ids().filter((id) => (key[id] as KeyEntry).kind === 'real') },
  ];

  const rows: ReturnType<typeof summarize>[] = [];
  const perRun: { run: string; judge: string; set: string; agree: number; cases: number; kappa: number }[] = [];
  const md: string[] = [];
  const total = (v: Verdict, set: string[]) => set.filter((id) => (key[id] as KeyEntry).label === v).length;

  md.push(
    '# Judge vs human labels',
    '',
    'Generated by `npm run report` from `runs/*.json` and `labels/key.json`. Do not edit by hand.',
    '',
    `Cases: ${items.length} (${VERDICTS.map((v) => `${total(v, ids())} ${v}`).join(', ')} by the human labels). Judges: ${judges.map((j) => `${j} × ${runsOf(j).length} runs`).join(', ')}. Each judge's verdict on a case is the majority of its runs (ties go to the stricter verdict).`,
    '',
  );

  // The headline: each model with each rubric, against the reviewer's labels and
  // against the labels as first drafted (before the reviewer changed 7 of them).
  const drafts = Object.fromEntries(Object.entries(key).map(([id, k]) => [id, { ...k, label: k.draft }]));
  const real = ids().filter((id) => (key[id] as KeyEntry).kind === 'real');
  md.push(
    '## Summary',
    '',
    '| Judge | Rubric | All cases: agreement | Kappa | Real criteria: weak tests caught | Subtler variants: agreement | Agreement with the first drafts |',
    '|---|---|---:|---:|---:|---:|---:|',
  );
  for (const judge of judges) {
    const rubric = runsOf(judge)[0]?.rubric ?? 'v1';
    const all = summarize(score(judge, runsOf(judge), ids(), key));
    const onReal = summarize(score(judge, runsOf(judge), real, key));
    const hard = summarize(score(judge, runsOf(judge), ids(2), key));
    const draft = summarize(score(judge, runsOf(judge), ids(), drafts));
    md.push(
      `| ${judge.replace(/-v\d$/, '')} | ${rubric} | ${all.agree}/${all.cases} = ${pct(all.agreement)} | ${k2(all.kappa)} | ${onReal.flags.caught}/${onReal.flags.weak} | ${hard.agree}/${hard.cases} | ${draft.agree}/${draft.cases} = ${pct(draft.agreement)} |`,
    );
  }
  md.push('');

  for (const set of sets) {
    md.push(`## ${set.name}`, '', '| Judge | Cases | Agreement (95% CI) | Kappa (95% CI) | Weighted kappa | Weak tests caught | False alarms |', '|---|---:|---|---|---:|---|---:|');
    for (const judge of judges) {
      const these = answered(judge, set.ids);
      if (!these.length) continue;
      const s = summarize(score(judge, runsOf(judge), these, key));
      if (set.name === 'All cases') rows.push(s);
      md.push(
        `| ${judge} | ${s.cases} | ${s.agree}/${s.cases} = ${pct(s.agreement)} (${ci(s.agreementCi, pct)}) | ${k2(s.kappa)} (${ci(s.kappaCi, k2)}), ${describeKappa(s.kappa)} | ${k2(s.weightedKappa)} | ${s.flags.caught}/${s.flags.weak} | ${s.flags.falseAlarms} |`,
      );
      for (const run of runsOf(judge)) {
        const one = summarize(score(run.name, [run], these, key));
        perRun.push({ run: run.name, judge, set: set.name, agree: one.agree, cases: one.cases, kappa: one.kappa });
      }
    }
    md.push('');
  }

  md.push('## Run to run', '', 'The same judge, the same prompts, answered three times in separate sessions.', '', '| Run | Agreement, all cases | Kappa |', '|---|---:|---:|');
  for (const r of perRun.filter((p) => p.set === 'All cases')) md.push(`| ${r.run} | ${r.agree}/${r.cases} | ${k2(r.kappa)} |`);
  md.push('');
  for (const judge of judges) {
    const these = answered(judge, ids());
    const u = unanimous(runsOf(judge).map((run) => these.map((id) => run.answers.find((a) => a.id === id)?.verdict as Verdict)));
    md.push(`- **${judge}:** all runs gave the same verdict on ${u.same} of ${u.n} cases.`);
  }
  md.push('');

  md.push('## Confusion (all cases, majority verdict)', '');
  for (const s of rows) {
    md.push(`**${s.judge}** (rows: human label, columns: judge)`, '', `| | ${VERDICTS.join(' | ')} |`, `|---|${VERDICTS.map(() => '---:').join('|')}|`);
    for (const h of VERDICTS) md.push(`| ${h} | ${VERDICTS.map((j) => s.confusion[h][j]).join(' | ')} |`);
    md.push('');
  }

  md.push('## Where a judge disagreed with the human label', '', 'Every case where at least one run disagreed. Verdicts listed per run.', '', '| Case | Where | Human | Runs | Reason given by the first disagreeing run |', '|---|---|---|---|---|');
  for (const item of items) {
    const k = key[item.id] as KeyEntry;
    const answers = runs.map((r) => ({ run: r.name, a: r.answers.find((a) => a.id === item.id) })).filter((x) => x.a);
    const off = answers.filter((x) => x.a?.verdict !== k.label);
    if (!off.length) continue;
    const where = `${k.feature} ${k.criterion}${k.variant ? ` (${k.variant})` : ''}`;
    const votes = answers.map((x) => `${x.run}: ${x.a?.verdict}`).join('<br>');
    md.push(`| ${item.id} | ${where} | ${k.label} | ${votes} | ${(off[0]?.a?.reason ?? '').replace(/\|/g, '\\|')} |`);
  }
  md.push('');

  // Added on Day 41: answers whose cited test is not in their own case's spec.
  const bad = badCitations(runs, items);
  const where = (id: string) => `${(key[id] as KeyEntry).feature} ${(key[id] as KeyEntry).criterion}`;
  md.push(
    '## Answers filed under the wrong case',
    '',
    `Every answer names the test it judged. ${bad.length} of ${runs.reduce((n, r) => n + r.answers.length, 0)} name a test that is not in their own case's spec. ${bad.filter((b) => b.kind === 'elsewhere').length} of those name a test from another feature's spec: the judge wrote its answer for one case under a neighbouring case's ID. The scores above count each answer under the ID it was filed under, as a pipeline reading the judge's output would. Found by \`src/attribution.ts\` on Day 41.`,
    '',
    '| Run | Filed under | Cited test | That test is in |',
    '|---|---|---|---|',
  );
  for (const b of bad) {
    const features = [...new Set(b.foundIn.map((id) => (key[id] as KeyEntry).feature))];
    md.push(`| ${b.run} | ${b.id} (${where(b.id)}) | ${b.test} | ${b.kind === 'elsewhere' ? `the ${features.join(', ')} spec` : 'no spec (invented)'} |`);
  }
  md.push('');

  const summary = JSON.stringify(
    {
      cases: items.length,
      labels: Object.fromEntries(VERDICTS.map((v) => [v, total(v, ids())])),
      judges: rows.map((s) => ({ ...s, kappaCi: s.kappaCi, agreementCi: s.agreementCi })),
      runs: perRun,
      badCitations: bad.map(({ run, id, test, kind }) => ({ run, id, test, kind })),
    },
    (_, v) => (typeof v === 'number' && !Number.isInteger(v) ? Math.round(v * 10000) / 10000 : v),
    2,
  );
  return { report: md.join('\n'), summary: summary + '\n' };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { report, summary } = build();
  const files: [string, string][] = [
    [path.join(PKG, 'REPORT.md'), report],
    [path.join(PKG, 'results', 'summary.json'), summary],
  ];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([f, c]) => !fs.existsSync(f) || lf(fs.readFileSync(f, 'utf8')) !== c);
    if (stale.length) {
      console.error(`Out of date (run npm run report): ${stale.map(([f]) => path.relative(PKG, f)).join(', ')}`);
      process.exit(1);
    }
    console.log('REPORT.md and results/summary.json are up to date');
  } else {
    fs.mkdirSync(path.join(PKG, 'results'), { recursive: true });
    for (const [f, c] of files) fs.writeFileSync(f, c);
    console.log(report.split('\n').slice(0, 30).join('\n'));
  }
}
